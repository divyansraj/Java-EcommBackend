package com.luffy.EcommerceBackend.model;

/**
 * Enum representing valid product categories in the e-commerce system.
 * Maps to the Mongoose schema's category enum (shortsleeves, longsleeves, sweatshirts, hoodies).
 */
public enum Category {
    SHORTSLEEVES,    // Short-sleeve shirts
    LONGSLEEVES,     // Long-sleeve shirts
    SWEATSHIRTS,     // Sweatshirts
    HOODIES          // Hoodies
}